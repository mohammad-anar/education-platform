/**
 * Builds the permission catalog, writes markdown documentation to docs/permission-catalog.md,
 * and returns the static typed list of permission definitions.
 *
 * @param {string} [outputPath] - Optional custom path for the generated markdown file.
 * @returns {IPermissionDefinition[]} The array of permission definitions.
 */
export const buildPermissionCatalog = (outputPath?: string): IPermissionDefinition[] => {
  const targetPath =
    outputPath ||
    path.resolve(process.cwd(), "docs", "permission-catalog.md");

  const lines: string[] = [
    "# System Permission Catalog",
    "",
    "> Auto-generated catalog mapping every active route and mutation in the system to fine-grained permission codes.",
    "",
    `**Total Permissions:** ${PERMISSION_CATALOG.length}`,
    "",
    "| Permission Code | Module | Resource | Action | Default Scope | Description |",
    "| :--- | :--- | :--- | :--- | :--- | :--- |",
  ];

  for (const perm of PERMISSION_CATALOG) {
    lines.push(
      `| \`${perm.code}\` | ${perm.module} | \`${perm.resource}\` | \`${perm.action}\` | \`${perm.defaultScope}\` | ${perm.description} |`,
    );
  }

  lines.push("");
  lines.push("## Scope Legend");
  lines.push("- **`OWN`**: User can only operate on records created by or owned by themselves.");
  lines.push("- **`ASSIGNED`**: User can operate on records explicitly assigned to them (e.g. Teacher's classes/courses, Guardian's wards).");
  lines.push("- **`INSTITUTE`**: User can operate across the entire tenant institute.");
  lines.push("- **`ALL`**: Cross-tenant or platform super-admin access.");
  lines.push("");

  const dir = path.dirname(targetPath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  fs.writeFileSync(targetPath, lines.join("\n"), "utf-8");

  return PERMISSION_CATALOG;
};

export default {
  PERMISSION_CATALOG,
  buildPermissionCatalog,
};
